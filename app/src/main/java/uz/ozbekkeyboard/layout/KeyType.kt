package uz.ozbekkeyboard.layout

enum class KeyType {
    CHARACTER,
    NUMBER,
    SPACE,
    SHIFT,
    BACKSPACE,
    ENTER,
    SWITCH_SYMBOLS, // switches between Alphabet and Symbols
    SWITCH_PAGE,    // switches between Symbol Page 1 (1/2) and Page 2 (2/2)
    GLOBE,          // switches IME
    COMMA,
    PERIOD
}
